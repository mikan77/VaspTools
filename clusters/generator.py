    def _summary_rows(self) -> list[dict[str, object]]:
        rows = []
        for order, cutoff in sorted(self.config.cutoffs.items()):
            clusters = self._clusters.get(order, [])
            rows.append(
                {
                    "order": order,
                    "cutoff_A": cutoff,
                    "neighbors_count": self._neighbor_counts[order],
                    "candidate_count": self._candidate_counts[order],
                    "unique_clusters": len(clusters),
                    "total_occurrences": sum(len(item.occurrences) for item in clusters),
                    "calculation_count": len(clusters),
                    "space_group": self._space_group_symbol,
                    "space_group_number": self._space_group_number,
                    "symmetry_operations": self._symmetry_operations_count,
                    "symmetry_method": "geometric_rmsd",
                }
            )
        return rows

    def _cluster_member_rows(self) -> list[dict[str, object]]:
        rows = []
        for cluster in self.cluster_types:
            for index, (instance_id, type_id) in enumerate(
                zip(cluster.member_instance_ids, cluster.member_type_ids)
            ):
                item = self._molecule_by_id[instance_id]
                distance = float(np.linalg.norm(item.com_cart_A - self._molecule_by_id[cluster.central_instance_id].com_cart_A))
                rows.append(
                    {
                        "cluster_type_id": cluster.cluster_type_id,
                        "member_index": index,
                        "molecule_instance_id": instance_id,
                        "molecule_type_id": type_id,
                        "is_central": index == 0,
                        "distance_to_central_A": distance,
                    }
                )
        return rows

    def _manifest_row(
        self,
        mode: str,
        object_type: str,
        object_id: str,
        order: int,
        path: Path,
    ) -> dict[str, object]:
        return {
            "calculation_id": f"CALC_{mode}_{object_id}",
            "mode": mode,
            "object_type": object_type,
            "object_id": object_id,
            "order": order,
            "input_path": str(path),
            "status": "prepared",
            "energy": None,
        }

    def _representative_molecules(self) -> dict[str, _MoleculeData]:
        representatives: dict[str, _MoleculeData] = {}
        for item in self._molecules:
            representatives.setdefault(item.type_id, item)
        return representatives

    def _public_molecule_instance(self, item: _MoleculeData) -> MoleculeInstance:
        return MoleculeInstance(
            molecule_instance_id=item.instance_id,
            molecule_type_id=item.type_id,
            source_atom_indices=item.source_atom_indices,
            translation=item.translation,
            com_cart_A=tuple(float(value) for value in item.com_cart_A),
            is_central=item.is_central,
        )

    def _public_cluster_type(self, cluster: _ClusterData) -> ClusterType:
        representative = cluster.occurrences[0][1]
        paths = self._cluster_paths.get(cluster.cluster_type_id, {})
        xyz_path = paths.get("xyz")
        full_inp_path = paths.get("full_inp")
        mbe_inp_path = paths.get("mbe_inp")
        return ClusterType(
            cluster_type_id=cluster.cluster_type_id,
            order=cluster.order,
            central_instance_id=representative[0],
            member_instance_ids=representative,
            member_type_ids=tuple(item.type_id for item in cluster.molecules),
            multiplicity=len(cluster.occurrences),
            cutoff_A=cluster.cutoff_A,
            fingerprint=cluster.fingerprint,
            xyz_path=xyz_path,
            inp_path=mbe_inp_path or full_inp_path,
            full_inp_path=full_inp_path,
            mbe_inp_path=mbe_inp_path,
        )

    def _replace_cluster_public_record(self, cluster: _ClusterData, updated: ClusterType) -> None:
        paths = self._cluster_paths.setdefault(cluster.cluster_type_id, {})
        paths["xyz"] = updated.xyz_path
        if updated.full_inp_path is not None:
            paths["full_inp"] = updated.full_inp_path
        if updated.mbe_inp_path is not None:
            paths["mbe_inp"] = updated.mbe_inp_path

    def _relative_path(self, path: Path | None, root: Path) -> str:
        if path is None:
            return ""
        try:
            return str(path.relative_to(root))
        except ValueError:
            return str(path)

    def _write_xyz(
        self,
        path: Path,
        molecules: Sequence[Molecule],
        comment: str,
    ) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        center = np.asarray(molecules[0].center_of_mass, dtype=float)
        atoms = []
        for molecule in molecules:
            for site in molecule.sites:
                coords = np.asarray(site.coords, dtype=float) - center
                atoms.append((site.specie.symbol, coords))
        lines = [str(len(atoms)), comment]
        lines.extend(
            f"{symbol} {coords[0]:.8f} {coords[1]:.8f} {coords[2]:.8f}"
            for symbol, coords in atoms
        )
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    @staticmethod
    def _write_csv(path: Path, rows: Sequence[dict[str, object]]) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        if not rows:
            path.write_text("\n", encoding="utf-8")
            return
        fields: list[str] = []
        for row in rows:
            for key in row:
                if key not in fields:
                    fields.append(key)
        with path.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=fields)
            writer.writeheader()
            writer.writerows(rows)
